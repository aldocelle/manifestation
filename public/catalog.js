export function dailyTip(d, date = new Date()) {
  const arr = tips[d.category] || tips.default;
  return arr[
    (Math.floor(date.getTime() / 86400000) +
      [...d.id].reduce((s, c) => s + c.charCodeAt(0), 0)) %
      arr.length
  ];
}
